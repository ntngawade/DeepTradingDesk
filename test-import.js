assert.equal(plan('AIAENG').setup,'QIT');
assert.equal(plan('AIAENG').timeframe,'W');
assert.equal(plan('JIOFIN').cmp,null,'Never invent an unavailable price');
assert.equal(plan('JIOFIN').timeframe,'125');
state.plans=rows.map(r=>r.p);
assert(importer.review(data.rows,found.row,found.map,state).every(r=>r.action==='Unchanged'),'Repeat upload must be idempotent');
